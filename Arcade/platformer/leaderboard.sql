create table if not exists public.asteroid_scores (
    id bigint generated by default as identity primary key,
    player_name text not null check (player_name ~ '^[A-Za-z0-9 -]{1,20}$'),
    score integer not null check (score between 1 and 1000000),
    created_at timestamptz not null default now()
);

alter table public.asteroid_scores
    drop constraint if exists asteroid_scores_player_name_check;
alter table public.asteroid_scores
    add constraint asteroid_scores_player_name_check
    check (player_name ~ '^[A-Za-z0-9 -]{1,20}$');

alter table public.asteroid_scores enable row level security;

grant select, insert on public.asteroid_scores to anon;

drop policy if exists "Anyone can read asteroid scores" on public.asteroid_scores;
create policy "Anyone can read asteroid scores"
    on public.asteroid_scores
    for select
    to anon
    using (true);

drop policy if exists "Anyone can submit asteroid scores" on public.asteroid_scores;
create policy "Anyone can submit asteroid scores"
    on public.asteroid_scores
    for insert
    to anon
    with check (
        score between 1 and 1000000
        and player_name ~ '^[A-Za-z0-9 -]{1,20}$'
    );

create index if not exists asteroid_scores_leaderboard_idx
    on public.asteroid_scores (score desc, created_at asc);
